"""Package the original MP4, byte-for-byte, into Qollab-sized JS modules.

Optional maintenance command: python dev/package_cutscene.py
No media tools or runtime build step required.
"""
import base64
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "cutscenes" / "full_intro_cutscene.mp4"
data = source.read_bytes()
output = root / "media"
output.mkdir(exist_ok=True)
names = []
for i, offset in enumerate(range(0, len(data), 1_000_000)):
    name = f"intro-{i}.js"
    encoded = base64.b64encode(data[offset:offset + 1_000_000]).decode("ascii")
    (output / name).write_text(f'// Generated MP4 bytes, part {i}.\nexport default "{encoded}";\n', encoding="utf-8")
    names.append(name)
imports = "\n".join(f"import part{i} from './{name}';" for i, name in enumerate(names))
parts = ", ".join(f"part{i}" for i in range(len(names)))
(output / "intro.js").write_text(
    f"// Generated by dev/package_cutscene.py; original video is preserved.\n{imports}\n"
    f"export const parts = [{parts}];\n"
    f"export const byteLength = {len(data)};\n"
    f"export const sha256 = '{hashlib.sha256(data).hexdigest()}';\n", encoding="utf-8")
print(f"Packaged {len(data):,} bytes in {len(names)} parts, each below 2 MB.")
